// Helper to get deterministic insurance subset based on seed
// This ensures consistent results between server and client (no hydration errors)
const getRandomInsurance = (count: number = 4, seed: string = '') => {
  // Create a simple hash from the seed string
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    const char = seed.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash; // Convert to 32bit integer
  }
  
  // Use hash to create a deterministic shuffle
  const shuffled = [...commonInsurance].sort((a, b) => {
    const hashA = (a.name.charCodeAt(0) + hash) % 1000;
    const hashB = (b.name.charCodeAt(0) + hash) % 1000;
    return hashA - hashB;
  });
  
  return shuffled.slice(0, count);
};

// Simple seeded random number generator for deterministic results
const seededRandom = (seed: number) => {
  let value = seed;
  return () => {
    value = (value * 9301 + 49297) % 233280;
    return value / 233280;
  };
};

// Helper to generate reviews deterministically
// Uses count and rating as seed to ensure consistent results
const generateReviews = (count: number, rating: number, seed: string = ''): any[] => {
  const reviews = [];
  const comments = [
    'Excellent care and very professional.',
    'Dr. was thorough and took time to explain everything.',
    'Great bedside manner and knowledgeable.',
    'Very satisfied with my visit.',
    'Highly recommend this doctor.',
    'Friendly staff and clean office.',
    'Felt heard and understood.',
    'Professional and caring approach.',
  ];
  
  // Create deterministic seed from parameters
  let seedValue = count * 1000 + Math.floor(rating * 100);
  if (seed) {
    for (let i = 0; i < seed.length; i++) {
      seedValue = ((seedValue << 5) - seedValue) + seed.charCodeAt(i);
      seedValue = seedValue & seedValue; // Convert to 32bit integer
    }
  }
  const random = seededRandom(Math.abs(seedValue) || 12345);
  
  for (let i = 0; i < count; i++) {
    // Use index in seed for each review to ensure determinism
    const reviewSeed = seedValue + i * 100;
    const reviewRandom = seededRandom(Math.abs(reviewSeed));
    
    reviews.push({
      id: `review-${i}`,
      patientName: `Patient ${i + 1}`,
      rating: Math.max(0, Math.min(5, rating + (reviewRandom() > 0.5 ? 0.5 : -0.5))),
      comment: comments[Math.floor(reviewRandom() * comments.length)],
      date: new Date(Date.now() - reviewRandom() * 90 * 24 * 60 * 60 * 1000).toISOString().split('T')[0],
      verified: reviewRandom() > 0.3,
    });
  }
  return reviews;
};

